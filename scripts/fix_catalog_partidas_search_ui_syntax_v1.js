const fs = require("fs");
const path = require("path");

const filePath = path.resolve(__dirname, "..", "src", "assets", "index.js");
const s0 = fs.readFileSync(filePath, "utf8");
let s = s0;
let changed = 0;

function replaceOnce(find, replace) {
  const idx = s.indexOf(find);
  if (idx === -1) return false;
  s = s.slice(0, idx) + replace + s.slice(idx + find.length);
  changed++;
  return true;
}

// Fix: incorrect e.jsxs call arg list introduced by UI patch
replaceOnce(
  'e.jsxs("div",{style:{position:"relative"}},children:[',
  'e.jsxs("div",{style:{position:"relative"},children:['
);

if (changed === 0) {
  console.log("OK: no hubo cambios.");
  process.exit(0);
}

fs.writeFileSync(filePath, s, "utf8");
console.log(`OK: fix UI Partidas de Obra aplicado (${changed} cambios).`);

